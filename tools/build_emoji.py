def norm(e):
    return e.replace("️", "")


def main(src):
    src = Path(src)
    notes = json.loads((src / "annotations.json").read_text())["annotations"]["annotations"]
    notes |= json.loads((src / "annotationsDerived.json").read_text())["annotationsDerived"]["annotations"]
    keywords = {norm(k): v.get("default", []) for k, v in notes.items()}
    groups, group = [], None
    for line in (src / "emoji-test.txt").read_text(encoding="utf-8").splitlines():
        if line.startswith("# group:"):
            name = line.split(":", 1)[1].strip()
            group = None if name == "Component" else [LABELS.get(name, name), []]
            if group:
                groups.append(group)
            continue
        if not group or line.startswith("#") or "; fully-qualified" not in line:
            continue
        emoji, name = re.match(r".*#\s+(\S+)\s+E[\d.]+\s+(.*)$", line).groups()
        if SKIN_TONES & set(emoji):
            continue
        name = name.replace("flag: ", "")
        words = set(name.lower().replace(":", " ").split())
        # Keyword phrases are split into words: search matches word by word anyway
        extra = []
        for phrase in keywords.get(norm(emoji), []) + ALIASES.get(emoji, "").split():
            for k in re.split(r"[\s:,]+", phrase.lower()):
                if k and k not in extra and k not in words:
                    extra.append(k)
        group[1].append("|".join([emoji, name, " ".join(extra)]))
    data = [[label, "\n".join(lines)] for label, lines in groups]
    OUT.write_text(
        "// Every fully-qualified emoji from Unicode's emoji-test.txt (Emoji 15.1), without skin-tone variants,\n"
        "// with CLDR keywords and a few slang aliases. Each group is [label, \"emoji|name|keywords\" lines].\n"
        "// Generated by tools/build_emoji.py; don't edit by hand.\n"
        "const EMOJI_GROUPS = " + json.dumps(data, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(sum(len(g[1]) for g in groups), "emoji written to", OUT)


if __name__ == "__main__":
    main(sys.argv[1])
